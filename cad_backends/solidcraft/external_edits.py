"""Owned edit snapshots and strict native-document comparison, not a CAD IR."""
from __future__ import annotations

import copy
import hashlib
import json
import math
import os
from pathlib import Path
import re
import stat

from mcp_server.errors import WorkflowFailure

EDIT_ID = re.compile(r"^edit-[a-z0-9_-]+$")
EXTERNAL_FILES = {"submitted_native": "submitted.solidcraft", "native_definition": "native-definition.json",
                  "reference_definition": "reference-definition.json", "external_provenance": "external-edit.json"}
MAX_NATIVE_BYTES = 8 * 1024**2
_LITERAL = re.compile(r"^\s*[+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?\s*(?:mm|cm|in)?\s*$")


def reject(message, *, stage="external_edit", classification="unsupported_capability", **details):
    raise WorkflowFailure(message, stage=stage, classification=classification, partial_result=details,
                          next_step="Keep the original accepted revision. Edit only supported dimensions in its prepared copy and resubmit deliberately.")


def read_owned(directory: Path, filename: str, *, limit=MAX_NATIVE_BYTES) -> bytes:
    """No-follow file descriptors close path races; special/hard-linked files fail."""
    try:
        directory_fd = os.open(directory, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW)
        try:
            descriptor = os.open(filename, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=directory_fd)
        finally:
            os.close(directory_fd)
        with os.fdopen(descriptor, "rb") as stream:
            before = os.fstat(stream.fileno())
            if not stat.S_ISREG(before.st_mode) or before.st_nlink != 1 or not 0 < before.st_size <= limit:
                raise ValueError("must be a bounded, ordinary file without hard links")
            data = stream.read(limit + 1)
            after = os.fstat(stream.fileno())
            if len(data) != before.st_size or (before.st_size, before.st_mtime_ns, before.st_ctime_ns) != (after.st_size, after.st_mtime_ns, after.st_ctime_ns):
                raise ValueError("file changed during snapshot")
            return data
    except (OSError, ValueError) as exc:
        reject(f"Unsafe, missing or changing edit file: {filename} ({exc}).", classification="validation_error")


def write_new(path: Path, data: bytes):
    with os.fdopen(os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600), "wb") as stream:
        stream.write(data)
        stream.flush()
        os.fsync(stream.fileno())


def sha256(data: bytes):
    return hashlib.sha256(data).hexdigest()


def definition(path: Path):
    try:
        return json.loads(read_owned(path.parent, path.name), parse_constant=lambda text: (_ for _ in ()).throw(ValueError(text)))
    except (ValueError, TypeError) as exc:
        reject(f"Invalid native definition: {exc}.", classification="verification_failed")


def canonical(document, expected):
    """Ignore only document display name and literal values of approved parameters.

    A reference is regenerated by SolidCraft itself, so every solved sketch value,
    constraint, expression, feature definition and dependency must still match.
    """
    if not isinstance(document, dict) or document.get("format") != "solidcraft/20" or document.get("units") != "mm":
        reject("Native format/units are outside the supported recipe contract.")
    result = copy.deepcopy(document)
    name = result.pop("name", None)
    if not isinstance(name, str) or len(name) > 256:
        reject("Native document display name is missing or invalid.")
    params = result.get("params")
    if not isinstance(params, list) or any(not isinstance(p, dict) for p in params):
        reject("Native parameter definitions are missing.")
    names = [p.get("name") for p in params]
    if any(not isinstance(name, str) for name in names) or len(names) != len(set(names)):
        reject("Native parameter names are invalid or duplicated.")
    for param in params:
        if param.get("name") in expected:
            if param.get("model") is not False or param.get("unit") != "mm" or not isinstance(param.get("expr"), str) or not _LITERAL.fullmatch(param["expr"]):
                reject("Only literal dimension values may change; parameter relationships must be preserved.")
            # Evaluated values were checked by the native health contract before
            # this comparison. Expressions of model parameters remain untouched.
            param["expr"] = {"expected_mm": expected[param["name"]]}
    if not set(expected).issubset(names):
        reject("Required authored dimensions are missing.")
    return result


def compare(reference, candidate, expected):
    reference, candidate = canonical(reference, expected), canonical(candidate, expected)
    mismatches = []
    def visit(a, b, path):
        if len(mismatches) >= 8:
            return
        if isinstance(a, bool) or isinstance(b, bool):
            equal = a is b
        elif isinstance(a, (int, float)) and isinstance(b, (int, float)):
            equal = math.isfinite(a) and math.isfinite(b) and abs(a - b) <= 1e-7
        elif isinstance(a, dict) and isinstance(b, dict):
            if a.keys() != b.keys():
                mismatches.append(path + ": fields changed")
            for key in sorted(a.keys() & b.keys()):
                visit(a[key], b[key], path + "/" + key)
            return
        elif isinstance(a, list) and isinstance(b, list):
            if len(a) != len(b):
                mismatches.append(path + ": entries changed")
            for i, (x, y) in enumerate(zip(a, b)):
                visit(x, y, path + f"/{i}")
            return
        else:
            equal = type(a) is type(b) and a == b
        if not equal:
            mismatches.append(path)
    visit(reference, candidate, "document")
    if mismatches:
        reject("Unsupported native feature, constraint or relationship edit.", mismatches=mismatches)
    return {"policy": "parent_native_regenerated_by_SolidCraft_v1", "passed": True,
            "ignored": ["document display name", "literal approved dimension expressions"],
            "numeric_serialization_tolerance": 1e-7}


def constrained(state):
    sketches = state.get("sketches")
    if not isinstance(sketches, list) or not sketches or any(s.get("fully_constrained") is not True or type(s.get("dof")) is not int or s["dof"] != 0 or s.get("status") != "solved" for s in sketches):
        reject("All recipe sketches must remain solved and fully constrained.", classification="verification_failed")
